import { expect, test, type Page } from '@playwright/test'
import * as fs from 'node:fs'
import * as path from 'node:path'
import { PORT, TOKEN, open } from './walk'

// V0 UI against a real Host: the keys chip, the Security setup screen, the five-screen path of the sign-in flow (token.issuer and the device key),
// the refusal banner, and the Show keys switch. The Host owns every rule. This spec drives the screens and reads what the Host sent.
const OUT = path.join(__dirname, '..', 'test-results', 'security-v0')
const shot = async (page: Page, name: string) => { fs.mkdirSync(OUT, { recursive: true }); await page.screenshot({ path: path.join(OUT, `${name}.png`) }) }
const api = (method: string, p: string, body?: unknown) =>
  fetch(`http://127.0.0.1:${PORT}${p}`, { method, headers: { Authorization: `Bearer ${TOKEN}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) })

test.describe.configure({ mode: 'serial' })

test('the top bar shows the keys chip, the security button, the Show keys switch and the OS transport button', async ({ page }) => {
  await open(page)
  await expect(page.getByTestId('keys-chip')).toHaveText(/Keys: built-in/)
  await expect(page.getByTestId('security-setup-button')).toBeVisible()
  await expect(page.getByTestId('show-keys-switch')).toBeChecked()
  await expect(page.getByTestId('transport-switch')).toHaveText('OS transport')
  await expect(page.getByText(/Real mode/)).toHaveCount(0)
  await shot(page, '01-top-bar')
})

test('the Show keys switch turns off and on, and the Host keeps the value', async ({ page }) => {
  await open(page)
  await page.getByTestId('show-keys-switch').uncheck()
  await expect.poll(async () => (await (await api('GET', '/api/security/show-keys')).json()).on).toBe(false)
  await page.getByTestId('security-setup-button').click()
  await expect(page.getByTestId('sec-test-keys-line')).toContainText('hides your keys on screen')
  await page.getByTestId('sec-show-keys-switch').check()
  await expect(page.getByTestId('show-keys-switch')).toBeChecked()
  await expect(page.getByTestId('sec-test-keys-line')).toHaveText('Use test keys only. This course shows your keys on screen and in saved files.')
})

test('the Security setup screen lists 15 types with the two-button mode switch and the states', async ({ page }) => {
  await open(page)
  await page.getByTestId('security-setup-button').click()
  await expect(page.getByTestId('sec-page')).toBeVisible()
  await expect(page.locator('[data-testid^="type-row-"]')).toHaveCount(15)
  const issuer = page.getByTestId('type-row-token.issuer')
  await expect(issuer.getByTestId('type-mode-builtin-token.issuer')).toHaveText('Built-in key')
  await expect(issuer.getByTestId('type-mode-mine-token.issuer')).toHaveText('My test key')
  await expect(page.getByTestId('type-state-token.issuer')).toHaveAttribute('data-state', 'builtin')
  await expect(page.getByTestId('type-action-token.issuer')).toHaveText('Set up my own')
  await expect(page.getByTestId('sec-page')).not.toContainText(/\bReal\b/)
  await shot(page, '02-security-setup')
})

test('a lesson whose key is not ready shows the refusal banner, and the built-in button runs the lesson', async ({ page }) => {
  expect((await api('PUT', '/api/security/types/token.issuer/mode', { mode: 'Mine' })).status).toBeLessThan(300)
  await open(page)
  await expect(page.getByTestId('keys-chip')).toHaveText(/Keys: 1 of mine/)
  await expect(page.getByTestId('security-badge')).toHaveText('1')
  await expect(page.getByTestId('lesson-keys-badge-10')).toBeVisible()
  await page.getByTestId('lesson-item-10').click()
  await page.getByRole('button', { name: /start tour/i }).click()
  const banner = page.getByTestId('security-needs-banner')
  await expect(banner).toContainText('Lesson 10 needs 1 key that still needs setting up.')
  await expect(page.getByTestId('needs-row-token.issuer')).toContainText('Token signing key')
  await expect(page.getByTestId('error-banner')).toHaveCount(0)
  await shot(page, '03-refusal-banner')
  await page.getByTestId('needs-use-builtin').click()
  await expect(page.getByTestId('needs-confirm')).toBeVisible()
  await page.getByTestId('needs-confirm-yes').click()
  await expect(banner).toHaveCount(0)
  await expect(page.getByTestId('keys-chip')).toHaveText(/Keys: built-in/)
  await expect.poll(async () => (await (await api('GET', '/api/security')).json()).types.find((t: any) => t.typeId === 'token.issuer').mode).toBe('BuiltIn')
})

test('walks the five screens of Make my sign-in set and ends with the two chips', async ({ page }) => {
  await open(page)
  await page.getByTestId('security-setup-button').click()
  await page.getByTestId('flow-my-login').click()
  const sheet = page.getByTestId('wizard-sheet')
  await expect(sheet).toBeVisible()
  // 1 of 5: Intro
  await expect(page.getByTestId('flow-my-login-intro')).toBeVisible()
  await expect(page.getByTestId('flow-part-progress')).toHaveText('Screen 1 of 5')
  await expect(page.getByTestId('wizard-test-keys-line')).toHaveText('Use test keys only. This course shows your keys on screen and in saved files.')
  await expect(page.getByTestId('wizard-next-reason')).toHaveText('')
  await shot(page, '04-intro')
  await page.getByTestId('wizard-next').click()
  // 2 of 5: Make it for me
  await expect(page.getByTestId('flow-my-login-make')).toBeVisible()
  await expect(page.getByTestId('flow-part-progress')).toHaveText('Screen 2 of 5')
  await expect(page.getByTestId('flow-part-token.issuer')).toBeVisible()
  await expect(page.getByTestId('flow-part-device.enrolment')).toContainText('Device key, no outside check')
  await expect(page.getByTestId('flow-files-link')).toHaveText('Use my own files')
  await expect(page.getByTestId('wizard-next')).toBeDisabled()
  await expect(page.getByTestId('wizard-next-reason')).not.toHaveText('')
  await shot(page, '05-make')
  await page.getByTestId('flow-make-button').click()
  // 3 of 5: Review
  await expect(page.getByTestId('flow-my-login-review')).toBeVisible()
  await expect(page.getByTestId('flow-part-progress')).toHaveText('Screen 3 of 5')
  await expect(page.getByTestId('review-algorithm-token.issuer')).toHaveText('Ed25519')
  await expect(page.getByTestId('review-fingerprint-token.issuer')).toContainText('SHA256:')
  await expect(page.getByTestId('wizard-fixed-dates')).toContainText('This lab')
  await shot(page, '06-review')
  await page.getByTestId('wizard-next').click()
  // 4 of 5: Check
  await expect(page.getByTestId('flow-my-login-check')).toBeVisible()
  await expect(page.getByTestId('flow-part-progress')).toHaveText('Screen 4 of 5')
  await page.getByTestId('flow-check-button').click()
  await expect(page.getByTestId('check-says-token.issuer')).toContainText('Checked with OpenSSL. This checks the signature only.')
  await expect(page.getByTestId('check-command-token.issuer')).toContainText('openssl pkeyutl -verify')
  await expect(page.getByTestId('check-output-token.issuer')).toContainText('Signature Verified Successfully')
  await expect(page.getByTestId('check-says-device.enrolment')).toContainText('Saved, no outside check')
  await shot(page, '07-check')
  await page.getByTestId('wizard-next').click()
  // 5 of 5: Done
  await expect(page.getByTestId('flow-my-login-done')).toBeVisible()
  await expect(page.getByTestId('flow-part-progress')).toHaveText('Screen 5 of 5')
  await expect(page.getByTestId('done-chip-token.issuer')).toContainText('Checked')
  await expect(page.getByTestId('done-chip-device.enrolment')).toContainText('Saved, no outside check')
  await shot(page, '08-done')
  await page.getByTestId('flow-done-map').click()
  await expect(sheet).toHaveCount(0)
  await expect(page.getByTestId('type-state-token.issuer')).toHaveAttribute('data-state', 'checked')
  await expect(page.getByTestId('type-state-device.enrolment')).toHaveAttribute('data-state', 'no-outside-check')
  await expect(page.getByTestId('keys-chip')).toHaveText(/Keys: 2 of mine/)
  await shot(page, '09-map-after')
})

test('Keep my place leaves the run open and the row reads Setup paused', async ({ page }) => {
  await api('PUT', '/api/security/types/token.issuer/mode', { mode: 'BuiltIn' })
  await api('PUT', '/api/security/types/device.enrolment/mode', { mode: 'BuiltIn' })
  await open(page)
  await page.getByTestId('security-setup-button').click()
  await page.getByTestId('flow-my-login').click()
  await page.getByTestId('wizard-next').click()
  await page.getByTestId('wizard-cancel').click()
  await expect(page.getByTestId('wizard-cancel-sheet')).toBeVisible()
  await shot(page, '10-cancel-sheet')
  await page.getByTestId('wizard-cancel-keep').click()
  await expect(page.getByTestId('wizard-sheet')).toHaveCount(0)
  await expect(page.getByTestId('flow-paused-my-login')).toBeVisible()
  await page.getByTestId('flow-my-login').click()
  await expect(page.getByTestId('flow-my-login-make')).toBeVisible()
  await page.getByTestId('wizard-cancel').click()
  await page.getByTestId('wizard-cancel-discard').click()
  await expect(page.getByTestId('wizard-sheet')).toHaveCount(0)
})
